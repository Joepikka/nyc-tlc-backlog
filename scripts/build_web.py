"""Build the offline dashboard data from the reconciled project exports."""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def records(name, text_fields, number_fields):
    with (ROOT / "exports" / name).open(encoding="utf-8-sig", newline="") as source:
        return [
            [row[field] for field in text_fields] + [int(row[field]) for field in number_fields]
            for row in csv.DictReader(source)
        ]


def main():
    daily = records("daily.csv", ("day", "problem", "borough"),
                    ("arrivals", "closures", "backlog", "aged30"))
    worklist = records("open_march31.csv", ("unique_key", "problem", "borough", "created_day"),
                       ("age_days",))
    bulk = json.loads((ROOT / "data/citywide-manifest.json").read_text(encoding="utf-8"))
    validation = json.loads((ROOT / "report/validation.json").read_text(encoding="utf-8"))
    cutoff = max(row[0] for row in daily)
    if len(worklist) != sum(row[5] for row in daily if row[0] == cutoff):
        raise ValueError("The review queue does not match the closing backlog.")
    payload = {
        "daily": daily,
        "worklist": worklist,
        "source": {
            "bytes": bulk["bytes"],
            "citywide": bulk["rows"],
            "tlc": validation["source_rows"],
            "firstDay": min(row[0] for row in daily),
            "lastDay": cutoff,
        },
    }
    target = ROOT / "web/data.js"
    target.write_text("// Generated by scripts/build_web.py.\nwindow.nycData = "
                      + json.dumps(payload, ensure_ascii=True, separators=(",", ":")) + ";\n",
                      encoding="utf-8")
    print(f"Wrote dashboard data for {len(daily):,} daily groups and {len(worklist):,} open requests.")


if __name__ == "__main__":
    main()
